/** Как модель должна интерпретировать отчёт механического аудита. */
const INTERPRETATION = `## КАК ЧИТАТЬ ОТЧЁТ seo_audit
Отчёт содержит score (0-100 по категориям с весами) и findings трёх уровней:
- error  — страница теряет трафик или не индексируется. Чинить в первую очередь.
- warn   — страница индексируется, но проигрывает конкурентам.
- info   — рекомендации на вырост, в отчёте клиенту идут отдельным блоком.

НИКОГДА не пересказывай findings дословно как единственный результат:
отчёт — это факты, твоя работа — приоритизация и план действий.
Сначала сгруппируй находки по темам (индексация, метатеги, разметка, контент,
перелинковка), потом оцени влияние на трафик и трудозатраты, потом дай план.`;

/** Контент и E-E-A-T: проверяет модель, читая текст страницы. */
const CONTENT_EEAT = `## КОНТЕНТ И E-E-A-T (оценивай по тексту страницы, а не по метрикам)
1. Интент. Закрывает ли страница намерение запроса: информационное (объяснить),
   коммерческое (сравнить и дать цену), транзакционное (заказать)?
   Признак промаха по интенту: по коммерческому запросу страница рассказывает,
   но не предлагает купить или оставить заявку.
2. Experience (опыт). Видны ли признаки реального опыта: свои цифры, кейсы,
   скриншоты, сроки, имена исполнителей, цены «от» с обоснованием?
   Шаблонный текст «мы команда профессионалов» опытом НЕ считается.
3. Expertise (экспертиза). Есть ли факты, которые не может написать дилетант:
   конкретные технологии, нормативы, типовые ошибки, сравнения решений?
4. Authorship. Понятно ли, кто автор и компания: страница «О студии», контакты,
   реквизиты, автор статьи с датой публикации и датой обновления?
5. Полнота. Перечисли 3-5 подвопросов, которые пользователь задаст после прочтения,
   и которых на странице нет. Это готовый план доработки контента.
6. Свежесть. Есть ли дата публикации/обновления. Для тем с меняющимися ценами
   и законодательством материал без даты — минус к доверию и к выдаче.
7. Уникальность формулировок. Канцелярит и пересказ общих мест снижают и CTR,
   и шансы попасть в ИИ-ответы: цитируют конкретные формулировки с цифрами.`;

/** GEO/AEO: пригодность страницы для ответов ИИ-поисковиков и ассистентов. */
const GEO_AEO = `## AI SEARCH / GEO / AEO (как страницу будут цитировать ИИ-ответы)
1. Answer-first: первый абзац после H1 отвечает на главный вопрос страницы
   одним-двумя предложениями с цифрой или конкретикой. ИИ-ответы цитируют именно его.
2. Самодостаточные блоки: каждый H2-раздел понятен БЕЗ контекста страницы,
   потому что ассистент вырывает его куском. Проверяй: вырежи раздел — он отвечает
   на свой подвопрос целиком?
3. Извлекаемые факты: таблицы, списки, определения вида «X — это …», цифры с
   единицами измерения. Сплошная простыня текста цитируется хуже таблицы.
4. FAQ-блок с разметкой FAQPage по реальным вопросам из выдачи и чатов,
   а не по выдуманным.
5. llms.txt и понятные человеку заголовки: ассистенты, читающие сайт напрямую,
   опираются на структуру, а не на визуальное оформление.
6. Запрет на воду: фразы без информации («в современном мире», «на сегодняшний день»)
   снижают плотность факта и шанс быть процитированным.`;

/** Подбор типа разметки schema.org под тип страницы. */
const SCHEMA_BY_PAGE_TYPE = `## РАЗМЕТКА schema.org: какой тип под какой тип страницы
- Главная и «О компании»      → Organization + LocalBusiness (адрес, гео, часы, телефон)
- Услуга                      → Service (+ Offer с ценой, если цена публичная)
- Статья блога                → BlogPosting/Article (author, datePublished, dateModified)
- Кейс                        → Article + review/rating только при реальной оценке клиента
- Цены                        → OfferCatalog с Offer по каждой позиции
- FAQ                         → FAQPage (вопрос-ответ дословно как на странице)
- Хлебные крошки на всех      → BreadcrumbList
- Контакты                    → ContactPoint внутри Organization

Правила: разметка обязана дублировать ВИДИМЫЙ текст (скрытый от пользователя
контент в schema приводит к санкциям); даты в ISO 8601; у LocalBusiness
обязательны name, address, telephone; один тип Organization на сайт,
а не по экземпляру на страницу.`;

/** Локальное SEO и сущности. */
const LOCAL_ENTITY = `## ЛОКАЛЬНОЕ SEO И СУЩНОСТИ
1. География названа текстом: город и районы в title, H1, первом абзаце,
   в контактах и в schema LocalBusiness.address — одинаково во всех местах.
2. NAP-консистентность: название, адрес, телефон идентичны на сайте,
   в картах и справочниках. Расхождение даже в написании ломает сущность.
3. Страницы под гео-запросы: «услуга + город» заслуживают отдельной страницы
   только при реальном отличии предложения (цена, сроки, кейсы по региону),
   иначе это дорвей и каннибализация.
4. Рецензируемые сущности: страница компании должна быть однозначно связана
   с внешними сущностями (карты, справочники, соцсети) через sameAs в schema.`;

/** Внутренняя перелинковка и архитектура. */
const LINKING_ARCHITECTURE = `## ПЕРЕЛИНКОВКА И АРХИТЕКТУРА
1. Коммерческие страницы получают ссылки из информационных статей по смыслу,
   с осмысленным анкором («стоимость SEO-продвижения»), а не «здесь».
2. Сироты: страницы без входящих внутренних ссылок не индексируются и не ранжируются.
3. Глубина: важные страницы достижимы за 3 клика от главной.
4. Каннибализация: две страницы под один интент с близкими title конкурируют
   между собой — объединить или развести интенты и перелинковать главную на одну.
5. Хлебные крошки присутствуют и размечены BreadcrumbList.`;

